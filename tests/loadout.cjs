const { chromium } = require('playwright');
const assert = require('node:assert/strict');
const fs = require('node:fs/promises');
const path = require('node:path');

(async () => {
  await fs.mkdir('test-results/loadout', { recursive: true });
  const browser = await chromium.launch({ executablePath: process.env.BROWSER_PATH || 'C:/Program Files (x86)/Microsoft/Edge/Application/msedge.exe', headless: true, args: ['--use-angle=swiftshader', '--enable-unsafe-swiftshader'] });
  try {
    const page = await browser.newPage({ viewport: { width: 1440, height: 900 } }), errors = [];
    page.on('pageerror', e => errors.push(e.message));
    page.on('console', m => { if (m.type() === 'error') errors.push(m.text()); });
    await page.goto('file:///' + path.join(process.cwd(), 'index.html').replaceAll('\\', '/') + '?test=1');
    await page.waitForFunction(() => document.body.dataset.ready === 'true', null, { timeout: 60000 });
    const click = id => page.evaluate(id => document.getElementById(id).click(), id);
    const equip = id => page.locator(`[data-equip="${id}"]`).click();
    const state = () => page.evaluate(() => window.__AN_HOA__.state());
    const advance = t => page.evaluate(t => window.__AN_HOA__.advance(t), t);
    await click('soundButton');
    await click('clearLoadout');
    assert.equal(await page.locator('#startButton').isDisabled(), true);
    const defenses = ['water-barrier', 'earth-barrier', 'ice-reflect', 'wood-barrier'];
    for (const id of defenses) await equip(id);
    assert.deepEqual((await state()).loadout, defenses, 'Defense spells can be selected first');
    assert.equal(await page.locator('#startButton').isDisabled(), true);
    assert.match(await page.locator('#loadoutNotice').textContent(), /ít nhất 1 chiêu tấn công/);
    await page.keyboard.press('Enter'); assert.equal((await state()).started, false);
    await click('startButton'); assert.equal((await state()).started, false);
    await equip('fire-orb');
    assert.equal(await page.locator('#startButton').isDisabled(), false);
    assert.equal(await page.locator('#loadoutBalance').textContent(), '1 công · 4 thủ');
    await page.screenshot({ path: 'test-results/loadout/one-attack-four-defenses.png' });
    await equip('water-orb');
    assert.equal((await state()).loadout.length, 5, 'Sixth spell stays out');
    await page.locator('[data-remove="fire-orb"]').click();
    assert.equal(await page.locator('#startButton').isDisabled(), true, 'Removing the last attack blocks entry');
    await page.keyboard.press('Enter'); assert.equal((await state()).started, false);
    await equip('fire-orb'); await click('startButton');
    await page.evaluate(() => window.__AN_HOA__.setAIEnabled(false));
    assert.equal((await state()).started, true);
    assert.deepEqual((await state()).equipped, [...defenses, 'fire-orb']);
    await page.keyboard.press('q'); await page.keyboard.press('w'); await page.keyboard.press('Space');
    await advance(1.8); assert.equal((await state()).enemyHealth, 957);
    await page.keyboard.press('Escape'); await click('changeLoadout'); await click('clearLoadout');
    const attacks = ['fire-orb', 'water-orb', 'light-orb', 'ice-orb', 'earth-orb'];
    for (const id of attacks) await equip(id);
    assert.deepEqual((await state()).loadout, attacks);
    assert.equal(await page.locator('#startButton').isDisabled(), false);
    assert.equal(await page.locator('#loadoutBalance').textContent(), '5 công · 0 thủ');
    await page.screenshot({ path: 'test-results/loadout/five-attacks.png' });
    await click('startButton');
    assert.deepEqual((await state()).equipped, attacks);
    assert.equal(await page.locator('[data-spell]').count(), 5);
    await page.reload();
    await page.waitForFunction(() => document.body.dataset.ready === 'true');
    assert.deepEqual((await state()).loadout, attacks, 'Saved all-attack loadout restores');
    assert.equal(await page.locator('#startButton').isDisabled(), false);
    assert.deepEqual(errors, []);
    console.log('PASS loadout: defense-first selection, required attack, removal/entry guards, 1 attack + 4 defenses, 5 attacks, five-slot cap, casting and saved-loadout restoration; no browser errors.');
  } finally { await browser.close(); }
})().catch(e => { console.error(e); process.exitCode = 1; });
